function fail(code){throw new Error(code);}
function getPath(root,key){
  let current=root;
  for(const part of String(key).split('.')){
    if(!current||!Object.prototype.hasOwnProperty.call(current,part))fail(`RC58_TOKEN_REFERENCE_MISSING:${key}`);
    current=current[part];
  }
  return current;
}
function resolveValue(root,value,stack=[]){
  if(typeof value==='string'){
    const match=value.match(/^\{([^}]+)\}$/);
    if(!match)return value;
    if(stack.includes(match[1]))fail(`RC58_TOKEN_REFERENCE_CYCLE:${[...stack,match[1]].join('>')}`);
    return resolveValue(root,getPath(root,match[1]),[...stack,match[1]]);
  }
  if(Array.isArray(value))return value.map((item)=>resolveValue(root,item,stack));
  if(value&&typeof value==='object'){
    return Object.fromEntries(Object.entries(value).map(([key,item])=>[key,resolveValue(root,item,stack)]));
  }
  return value;
}
function resolveTokens(raw){return resolveValue(raw,raw);}
function numberText(value){
  const numeric=Number(value);
  if(!Number.isFinite(numeric))fail(`RC58_TOKEN_NUMBER_REQUIRED:${value}`);
  return Number.isInteger(numeric)?String(numeric):String(Number(numeric.toFixed(4)));
}
function rem(px){return `${numberText(Number(px)/16)}rem`;}
function px(value){return `${numberText(value)}px`;}
function ms(value){return `${numberText(value)}ms`;}
function cssVar(name,value){return `  --iberfit-${name}: ${value};`;}
function rgbaToAndroid(value){
  const hex=String(value).match(/^#([0-9a-f]{6})$/i);
  if(hex)return `#FF${hex[1].toUpperCase()}`;
  const rgba=String(value).match(/^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(0(?:\.\d+)?|1(?:\.0+)?)\s*\)$/i);
  if(!rgba)fail(`RC58_ANDROID_COLOR_UNSUPPORTED:${value}`);
  const channels=rgba.slice(1,4).map((item)=>Number(item));
  if(channels.some((item)=>item<0||item>255))fail(`RC58_ANDROID_COLOR_RANGE:${value}`);
  const alpha=Math.round(Number(rgba[4])*255);
  const h=(number)=>number.toString(16).padStart(2,'0').toUpperCase();
  return `#${h(alpha)}${channels.map(h).join('')}`;
}
function xmlEscape(value){
  return String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&apos;');
}
function ensureRequired(t){
  const required=[
    'version','color.primitive.forest950','color.primitive.forest900','color.primitive.gold500',
    'color.primitive.gold300','color.primitive.cream100','color.primitive.cream300',
    'color.semantic.canvas','color.semantic.textPrimary','color.semantic.textSecondary',
    'color.semantic.border','color.semantic.focus','space.4','radius.sm',
    'size.touchTargetPx','motion.duration.standardMs','breakpoint.mobilePx','breakpoint.tabletPx'
  ];
  for(const key of required)getPath(t,key);
  if(Number(t.size.touchTargetPx)<44)fail('RC58_TOUCH_TARGET_BELOW_44');
  const series=Object.entries(t.color.dataViz).filter(([key])=>key.startsWith('series')).map(([,value])=>value);
  if(series.length<6||new Set(series).size!==series.length)fail('RC58_DATA_VIZ_SERIES_REQUIRED');
}
function buildJs(t){
  return `/* AUTO-GENERATED by scripts/generate_rc58_design_tokens.mjs. Do not edit. */\n`+
`function deepFreeze(value){\n`+
`  if(value&&typeof value==='object'&&!Object.isFrozen(value)){\n`+
`    Object.freeze(value);\n`+
`    for(const item of Object.values(value))deepFreeze(item);\n`+
`  }\n`+
`  return value;\n`+
`}\n\n`+
`export const IBERFIT_DESIGN_TOKENS=deepFreeze(${JSON.stringify(t,null,2)});\n`;
}
