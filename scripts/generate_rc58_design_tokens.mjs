function buildAndroidXml(t){
  const colors={
    iberfit_color_canvas:t.color.semantic.canvas,
    iberfit_color_surface_base:t.color.semantic.surfaceBase,
    iberfit_color_surface_raised:t.color.semantic.surfaceRaised,
    iberfit_color_text_primary:t.color.semantic.textPrimary,
    iberfit_color_text_secondary:t.color.semantic.textSecondary,
    iberfit_color_accent:t.color.semantic.accent,
    iberfit_color_accent_strong:t.color.semantic.accentStrong,
    iberfit_color_border:t.color.semantic.border,
    iberfit_color_focus:t.color.semantic.focus,
    iberfit_color_success:t.color.semantic.success,
    iberfit_color_warning:t.color.semantic.warning,
    iberfit_color_danger:t.color.semantic.danger,
    iberfit_color_info:t.color.semantic.info,
    iberfit_color_admin_accent:t.color.role.adminAccent,
  };
  const lines=[
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- AUTO-GENERATED by scripts/generate_rc58_design_tokens.mjs. Do not edit. -->',
    '<resources>'
  ];
  for(const [name,value] of Object.entries(colors))lines.push(`    <color name="${name}">${xmlEscape(rgbaToAndroid(value))}</color>`);
  for(const [key,value] of Object.entries(t.space))lines.push(`    <dimen name="iberfit_space_${key}">${numberText(value)}dp</dimen>`);
  for(const [key,value] of Object.entries(t.radius))if(key!=='pill')lines.push(`    <dimen name="iberfit_radius_${key}">${numberText(value)}dp</dimen>`);
  lines.push(`    <dimen name="iberfit_touch_target">${numberText(t.size.touchTargetPx)}dp</dimen>`);
  lines.push(`    <dimen name="iberfit_touch_target_comfortable">${numberText(t.size.touchTargetComfortablePx)}dp</dimen>`);
  lines.push('</resources>');
  lines.push('');
  return lines.join('\n');
}
function normalizeEol(value){return String(value).replace(/\r\n/g,'\n');}
function writeOrCheck(file,content,check){
  const normalized=normalizeEol(content);
  if(check){
    if(!fs.existsSync(file))fail(`RC58_GENERATED_FILE_MISSING:${path.relative(ROOT,file)}`);
    if(normalizeEol(fs.readFileSync(file,'utf8'))!==normalized)fail(`RC58_GENERATED_FILE_STALE:${path.relative(ROOT,file)}`);
    return;
  }
  fs.mkdirSync(path.dirname(file),{recursive:true});
  fs.writeFileSync(file,normalized,'utf8');
}
